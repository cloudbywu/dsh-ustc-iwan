test('updates only the GUI file, backs up confidentially, and rolls back exact original bytes from a new manager', async t => {
  const before = '\uFEFF' + (BASE + '  route-exclude-address: [] # empty GUI list\n  stack: mixed\nother: "💡"\n').replaceAll('\n', '\r\n')
  const f = fixture(t, { config: before, relays: [A] })
  const dry = await f.manager.inspect()
  const applied = await f.manager.apply({ mode: 'relay', revision: dry.revision })
  assert.equal(applied.state, 'ready')
  assert.equal(applied.rollbackAvailable, true)
  assert.equal(read(f.cfg), before.replace('[] # empty GUI list\r\n', ' # empty GUI list\r\n  - ' + A + '/32\r\n'))
  assert.equal(read(f.verge), VERGE)
  assert.equal(read(f.runtime), runtimeBase)
  const names = markers(f.dir)
  assert.equal(names.length, 1)
  const backup = path.join(f.dir, names[0])
  const other = TEMP_PREFIX + 'backup-' + '0'.repeat(64)
  fs.writeFileSync(path.join(f.dir, other), 'unrelated backup')
  assert.equal(fs.readFileSync(backup).includes(Buffer.from('LOCAL_FIXTURE_SECRET')), false)
  if (process.platform !== 'win32') assert.equal(fs.statSync(backup).mode & 0o077, 0)
  assert.notEqual(applied.revision, dry.revision)
  const newManager = createClashTunManager({ testOnly: f.testOnly })
  const rolled = await newManager.rollback({ revision: applied.revision })
  assert.equal(rolled.rollbackAvailable, false)
  assert.equal(rolled.result, 'rolled-back')
  assert.deepEqual(fs.readFileSync(f.cfg), Buffer.from(before))
  assert.deepEqual(rolled.modes.relay.missing, [A + '/32'])
  assert.deepEqual(markers(f.dir), [other])
  assert.equal(read(path.join(f.dir, other)), 'unrelated backup')
})

