test('rollback hash verification failure preserves the consumed candidate and releases the lock', async t => {
  const f = fixture(t, { relays: [A] })
  const s = await f.manager.apply({ mode: 'relay', revision: (await f.manager.inspect()).revision })
  const names = markers(f.dir)
  assert.equal(names.length, 1)
  const encrypted = fs.readFileSync(path.join(f.dir, names[0]))
  let polls = 0
  f.p.running = () => {
    if (++polls === 3) {
      assert.ok(markers(f.dir).includes(TEMP_PREFIX + 'lock'))
      fs.appendFileSync(f.cfg, '# external immediately after replace\n')
    }
    return false
  }
  await assert.rejects(f.manager.rollback({ revision: s.revision }), assertSafeError(500))
  assert.equal(read(f.cfg), BASE + '# external immediately after replace\n')
  assert.deepEqual(markers(f.dir), names)
  assert.deepEqual(fs.readFileSync(path.join(f.dir, names[0])), encrypted)
})

test('a replacement at the consumed backup path is never deleted, even with the same bytes', async t => {
  const f = fixture(t, { relays: [A] })
  const s = await f.manager.apply({ mode: 'relay', revision: (await f.manager.inspect()).revision })
  const [name] = markers(f.dir)
  const backup = path.join(f.dir, name)
  const displaced = path.join(f.dir, 'displaced-backup')
  const encrypted = fs.readFileSync(backup)
  let polls = 0
  f.p.running = () => {
    if (++polls === 3) {
      fs.renameSync(backup, displaced)
      fs.writeFileSync(backup, encrypted, { flag: 'wx' })
    }
    return false
  }
  const rolled = await f.manager.rollback({ revision: s.revision })
  assert.equal(rolled.result, 'rolled-back')
  assert.equal(read(f.cfg), BASE)
  assert.deepEqual(markers(f.dir), [name])
  assert.deepEqual(fs.readFileSync(backup), encrypted)
  assert.deepEqual(fs.readFileSync(displaced), encrypted)
})

