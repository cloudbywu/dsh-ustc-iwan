test('late running and unknown process observations block writes and rollback', async t => {
  const f = fixture(t, { relays: [A] })
  let s = await f.manager.inspect()
  let polls = 0
  f.p.running = () => ++polls >= 2
  await assert.rejects(f.manager.apply({ mode: 'relay', revision: s.revision }), assertSafeError(423))
  assert.equal(read(f.cfg), BASE)
  assert.equal((await f.manager.inspect()).state, 'running')
  f.p.running = () => undefined
  assert.equal((await f.manager.inspect()).state, 'unsupported')
  f.p.running = () => false
  s = await f.manager.inspect()
  s = await f.manager.apply({ mode: 'relay', revision: s.revision })
  polls = 0
  f.p.running = () => ++polls >= 2
  const beforeRollback = markers(f.dir).sort()
  await assert.rejects(f.manager.rollback({ revision: s.revision }), assertSafeError(423))
  assert.deepEqual(markers(f.dir).sort(), beforeRollback)
  assert.ok(read(f.cfg).includes(A + '/32'))
})

test('late file edits survive both apply and rollback; fresh rollback cannot erase them', async t => {
  const f = fixture(t, { relays: [A] })
  let s = await f.manager.inspect()
  let polls = 0
  f.p.running = () => {
    if (++polls === 2) fs.appendFileSync(f.cfg, '# external after backup\n')
    return false
  }
  await assert.rejects(f.manager.apply({ mode: 'relay', revision: s.revision }), assertSafeError(409))
  assert.equal(read(f.cfg), BASE + '# external after backup\n')
  assert.equal(markers(f.dir).filter(x => x.includes('backup')).length, 1)
  f.p.running = () => false
  s = await f.manager.apply({ mode: 'relay', revision: (await f.manager.inspect()).revision })
  assert.equal(s.rollbackAvailable, true)
  polls = 0
  f.p.running = () => {
    if (++polls === 2) fs.appendFileSync(f.cfg, '# external before rollback\n')
    return false
  }
  await assert.rejects(f.manager.rollback({ revision: s.revision }), assertSafeError(409))
  f.p.running = () => false
  s = await f.manager.inspect()
  assert.equal(s.rollbackAvailable, false)
  await assert.rejects(f.manager.rollback({ revision: s.revision }), assertSafeError(409))
  assert.match(read(f.cfg), /external before rollback/)
})

test('exclusive lock protects multiple manager instances and is never stolen', async t => {
  const f = fixture(t, { relays: [A] })
  const other = createClashTunManager({ testOnly: f.testOnly })
  const s = await f.manager.inspect()
  const lock = path.join(f.dir, TEMP_PREFIX + 'lock')
  fs.writeFileSync(lock, 'externally owned', { flag: 'wx' })
  await assert.rejects(f.manager.apply({ mode: 'relay', revision: s.revision }), assertSafeError(409))
  assert.equal(read(lock), 'externally owned')
  fs.unlinkSync(lock)
  const raced = await Promise.allSettled([f.manager.apply({ mode: 'relay', revision: s.revision }), other.apply({ mode: 'campus', revision: s.revision })])
  assert.deepEqual(raced.map(r => r.status).sort(), ['fulfilled', 'rejected'])
  assert.equal(markers(f.dir).length, 1)
})

