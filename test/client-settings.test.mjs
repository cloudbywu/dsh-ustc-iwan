  disclosure.props.onClick();ui.render()
  assert.equal(ui.button('▾ 收起高级设置').props['aria-expanded'],true)
  assert.equal(save(ui).props.disabled,true)
  assert.doesNotMatch(save(ui).props.className,/primary/)
